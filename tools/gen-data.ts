// Development only. Converts WaveDrom's skins and text-width table into
// ewavedrom-data.el.  Usage: bun tools/gen-data.ts > ewavedrom-data.el

import { readdirSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "node_modules", "wavedrom");
const stringify = require(join(import.meta.dir, "node_modules/onml/stringify.js"));
const pkg = require(join(root, "package.json"));
const charWidth = require(join(root, "lib", "char-width.json"));

const skinDir = join(root, "skins");
const skins: Record<string, any> = {};
for (const f of readdirSync(skinDir).filter((f) => f.endsWith(".js")).sort()) {
  Object.assign(skins, require(join(skinDir, f)));
}

const el = (s: string) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

const out: string[] = [];
out.push(";;; ewavedrom-data.el --- WaveDrom skins and font metrics as data  -*- lexical-binding: t; -*-");
out.push("");
out.push(`;; Generated by tools/gen-data.ts from wavedrom ${pkg.version}.  Do not edit.`);
out.push(";; Skin artwork Copyright (c) 2011-2024 Aliaksei Chapyzhenka, MIT licence.");
out.push("");
out.push(";;; Commentary:");
out.push("");
out.push(";; Each skin is (NAME :head ATTRS :socket (W H X Y) :defs STRING).  ATTRS are");
out.push(";; the root <svg> attributes before rendering, :socket is the brick geometry");
out.push(";; WaveDrom reads from the skin, and :defs is the serialised <style> and <defs>.");
out.push("");
out.push(";;; Code:");
out.push("");
out.push(`(defconst ewavedrom-skins-version ${el(pkg.version)}`);
out.push('  "WaveDrom release the vendored skins were taken from.")');
out.push("");
out.push("(defconst ewavedrom-skins");
out.push("  '(");
for (const name of Object.keys(skins)) {
  const skin = skins[name];
  const head = Object.entries(skin[1])
    .map(([k, v]) => `(${el(k)} . ${el(String(v))})`)
    .join(" ");
  const socket = skin[3][1][2][1];
  const defs = skin.slice(2, -1).map((e: any) => stringify(e)).join("");
  out.push(`    (${el(name)}`);
  out.push(`     :head (${head})`);
  out.push(`     :socket (${socket.width} ${socket.height} ${socket.x} ${socket.y})`);
  out.push(`     :defs ${el(defs)})`);
}
out.push("    )");
out.push('  "WaveDrom skins, keyed by the name `config.skin\' selects.")');
out.push("");
out.push("(defconst ewavedrom-char-widths");
out.push("  [" + charWidth.chars.join(" ") + "]");
out.push('  "Helvetica advance widths per UTF-16 code unit, in hundredths of the font size.")');
out.push("");
out.push(`(defconst ewavedrom-char-width-other ${charWidth.other}`);
out.push('  "Width used for code units outside `ewavedrom-char-widths\'.")');
out.push("");
out.push("(provide 'ewavedrom-data)");
out.push(";;; ewavedrom-data.el ends here");
process.stdout.write(out.join("\n") + "\n");
